#define FP_RANDOM_NONCE_LEN CONFIG_BT_FAST_PAIR_FHN_RANDOM_NONCE_LEN

static void eik_storage_setup(void)
{
	int err;

	err = settings_subsys_init();
	zassert_ok(err, "settings_subsys_init failed");

	err = settings_load();
	zassert_ok(err, "settings_load failed");

	err = fp_storage_init();
	zassert_ok(err, "fp_storage_init failed");
}

static void eik_before(void *fixture)
{
	ARG_UNUSED(fixture);

	if (!IS_ENABLED(CONFIG_BT_FAST_PAIR_FHN_EIK_SPE)) {
		eik_storage_setup();
	}

	zassert_ok(fp_fhn_eik_delete(), "EIK delete failed");
	zassert_equal(fp_fhn_eik_is_provisioned(), 0, "EIK not unprovisioned");
}

static void eik_after(void *fixture)
{
	ARG_UNUSED(fixture);

	zassert_ok(fp_fhn_eik_delete(), "EIK delete failed");
}

